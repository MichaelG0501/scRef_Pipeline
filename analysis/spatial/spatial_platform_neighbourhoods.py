def read_sample_design():
    design = pd.read_csv(SAMPLE_DESIGN, sep='\t', dtype=str)
    required = ['platform', 'orig.ident', 'donor_id', 'treatment_timepoint']
    if list(design.columns) != required or design.isna().any().any():
        raise ValueError('Malformed sample design')
    if design.duplicated(['platform', 'orig.ident']).any():
        raise ValueError('Duplicate sample identity in the study design')
    if design.groupby('donor_id')['platform'].nunique().max() != 1:
        raise ValueError('The study design contains a donor shared across platforms')
    if design.groupby('platform')['donor_id'].nunique().to_dict() != {'visium_hd': 2, 'xenium': 6}:
        raise ValueError('Expected two Visium HD donors and six independent Xenium donors')
    return design


def bh_adjust(values):
    values = np.asarray(values, dtype=float)
    result = np.full(values.shape, np.nan)
    ok = np.isfinite(values)
    p = values[ok]
    order = np.argsort(p)
    if len(p):
        adjusted = np.minimum.accumulate((p[order] * len(p) / np.arange(1, len(p) + 1))[::-1])[::-1]
        reordered = np.empty(len(p))
        reordered[order] = np.minimum(adjusted, 1)
        result[ok] = reordered
    return result


def apply_fdr(frame, pcol, outcol, keys):
    frame[outcol] = np.nan
    for indices in frame.groupby(keys, sort=False, dropna=False).groups.values():
        frame.loc[indices, outcol] = bh_adjust(frame.loc[indices, pcol])
    return frame


def strict_bool(values):
    if values.dtype == bool:
        return values.to_numpy()
    mapped = values.astype(str).str.lower().map({'true': True, 'false': False})
    if mapped.isna().any():
        raise ValueError('Non-boolean eligibility or malignancy values')
    return mapped.to_numpy(dtype=bool)


