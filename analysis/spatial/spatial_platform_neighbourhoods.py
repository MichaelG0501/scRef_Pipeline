    ordered = design.sort_values(['platform', 'donor_id', 'treatment_timepoint'])
    with PdfPages(path) as pdf:
        for mode, page in primary.groupby('mode_id', sort=True):
            # Selection is explicit and reproducible. These panels illustrate
            # heterogeneity; the complete testing families remain in the tables.
            chosen = page.sort_values(['replication_fdr', 'pooled_fdr'], na_position='last').head(5)
            fig, axes = plt.subplots(len(chosen), 1, figsize=(183 / 25.4, 235 / 25.4), squeeze=False)
            fig.subplots_adjust(left=.34, right=.96, top=.90, bottom=.10, hspace=.90)
            for ax, (_, interaction) in zip(axes[:, 0], chosen.iterrows()):
                mask = np.ones(len(sections), dtype=bool)
                donor_mask = np.ones(len(donors), dtype=bool)
                for key in KEYS:
                    mask &= sections[key].to_numpy() == interaction[key]
                    donor_mask &= donors[key].to_numpy() == interaction[key]
                points = sections.loc[mask & sections['eligible_pair']].set_index('sample_id')
                donor_points = donors.loc[donor_mask].set_index('donor_id')
                for position, (_, sample_info) in enumerate(ordered.iterrows()):
                    sample_id = sample_info['sample_id']
                    if sample_id in points.index:
                        ax.scatter(points.loc[sample_id, 'log2_enrichment'], position, s=15,
                                   color=PLATFORM_COLOURS[sample_info['platform']], zorder=3)
                    else:
                        ax.text(.99, position, 'unavailable', transform=ax.get_yaxis_transform(),
                                ha='right', va='center', color='#666666', fontsize=7)
                for donor_id, donor in donor_points.iterrows():
                    positions = np.flatnonzero(ordered['donor_id'].to_numpy() == donor_id)
                    ax.scatter(donor['log2_enrichment'], float(positions.mean()), marker='D', s=21,
                               facecolors='none', edgecolors='black', linewidths=.6, zorder=4)
                labels = [f"{r['orig.ident']} ({r['treatment_timepoint']})" if r['platform'] == 'visium_hd'
                          else r['orig.ident'] for _, r in ordered.iterrows()]
