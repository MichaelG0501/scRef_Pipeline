def local_groups(target, parent_restricted):
    group_sets = []
    fractions = []
    x = target['spatial_x'].to_numpy()
    y = target['spatial_y'].to_numpy()
    parent = target['target_type'].to_numpy()
    for ox, oy in [(0, 0), (160, 0), (0, 160), (160, 160)]:
        keys = list(zip(np.floor((x + ox) / 320).astype(int), np.floor((y + oy) / 320).astype(int)))
        if parent_restricted:
            keys = [(p, a, b) for p, (a, b) in zip(parent, keys)]
        labels = pd.Series(keys, dtype='object')
        groups = [np.asarray(v, dtype=np.int64) for v in labels.groupby(labels, sort=False).indices.values()]
        groups = [g for g in groups if len(g) > 1]
        movable = sum(map(len, groups)) / len(target)
        if movable < 0.5:
            raise ValueError(f'Local permutation mobility below 50%: {movable}')
        group_sets.append(groups)
        fractions.append(movable)
    return group_sets, min(fractions)


def permutation_chunk(task):
    n, seed, start = task
    weights, membership, groups, observed = PERM_CONTEXT
    rng = np.random.default_rng(seed)
    shape = (len(groups),) + observed.shape
    total = np.zeros(shape)
    sumsq = np.zeros(shape)
    ge = np.zeros(shape, dtype=np.int64)
    le = np.zeros(shape, dtype=np.int64)
    origin_n = np.zeros(len(groups), dtype=np.int64)
    for iteration in range(n):
        origin = (start + iteration) % len(groups)
        perm = np.arange(membership.shape[0])
        for group in groups[origin]:
            perm[group] = rng.permutation(group)
        count = (weights @ membership[perm]).toarray()
        total[origin] += count
        sumsq[origin] += count ** 2
        ge[origin] += count >= observed
        le[origin] += count <= observed
        origin_n[origin] += 1
    return origin_n, total, sumsq, ge, le


def empirical_test(weights, membership, groups, n_perm, seed, n_workers):
    global PERM_CONTEXT
    observed = (weights @ membership).toarray()
    PERM_CONTEXT = (weights, membership, groups, observed)
    total_draws = n_perm * len(groups)
    chunks = np.array_split(np.arange(total_draws), min(8, total_draws))
    tasks = [(len(chunk), seed + i * 17011, int(chunk[0])) for i, chunk in enumerate(chunks)]
    with mp.get_context('fork').Pool(min(n_workers, len(tasks))) as pool:
        summaries = pool.map(permutation_chunk, tasks)
    origin_n, total, sumsq, ge, le = [sum(parts) for parts in zip(*summaries)]
    if not np.all(origin_n == n_perm):
        raise ValueError('Incorrect permutation count within a tile origin')
    origin_mean = total / origin_n[:, None, None]
    total_sum = total.sum(axis=0)
    mean = total_sum / total_draws
    sd = np.sqrt(np.maximum(0, (sumsq.sum(axis=0) - total_sum ** 2 / total_draws) / (total_draws - 1)))
    origin_p = np.minimum(1, 2 * np.minimum((ge + 1) / (origin_n[:, None, None] + 1),
                                           (le + 1) / (origin_n[:, None, None] + 1)))
    directions = np.sign(observed[None, :, :] - origin_mean)
    concordant = np.all(directions > 0, axis=0) | np.all(directions < 0, axis=0)
    p = np.where(concordant, origin_p.max(axis=0), 1.)
    PERM_CONTEXT = None
    audit = {'n': origin_n, 'mean': origin_mean, 'ge': ge, 'le': le,
             'p': origin_p, 'direction_concordant': concordant}
    return observed, mean, sd, p, audit


def build_sample(frame, sample, mp_order):
    scores = pd.read_csv(XOUT / f'intermediate/Auto_{sample}_ucell_scores.csv.gz').set_index('row_index')
    audit = pd.read_csv(XOUT / f'tables/Auto_{sample}_ucell_feature_audit.csv')
    audit['eligible'] = strict_bool(audit['eligible'])
    if audit['feature_id'].duplicated().any() or audit['feature_id'].isna().any():
        raise ValueError(f'{sample}: duplicate or missing UCell audit features')
    if set(audit['feature_id']) != set(scores.columns):
        raise ValueError(f'{sample}: score columns and audited signatures differ')
    if set(audit['sample']) != {sample}:
        raise ValueError(f'{sample}: UCell audit sample identity mismatch')
    if scores.index.duplicated().any() or set(scores.index) != set(frame['row_index']):
        raise ValueError(f'{sample}: UCell row identity mismatch')
    scores = scores.reindex(frame['row_index'])
    if set(audit.loc[audit['feature_side'] == 'malignant_source', 'feature_id']) != {f'cancer__{m}' for m in mp_order}:
        raise ValueError(f'{sample}: not all 17 malignant MPs were audited')
    malignant = frame['malignant'].to_numpy(dtype=bool)
    source_rows = np.flatnonzero(malignant)
    target_rows = np.flatnonzero(frame['target_type'].to_numpy() != 'excluded')
    sources, source_meta, source_audit = [], [], []
    for feature in mp_order + STATES:
        if feature in mp_order:
            fid = f'cancer__{feature}'
            a = audit.loc[audit['feature_id'] == fid].iloc[0]
            values = scores[fid].to_numpy()[source_rows]
            if not np.isfinite(values).all() or not np.isfinite(a['cutoff']):
                raise ValueError(f'{sample}: non-finite malignant scores or cutoff for {fid}')
            present = values > a['cutoff']
            if present.sum() != a['n_positive']:
                raise ValueError(f'{sample}: malignant positivity audit mismatch for {fid}')
            kind = 'cancer_mp'
            cutoff = a['cutoff']
        else:
            present = frame['state'].to_numpy()[source_rows] == feature
            kind = 'cancer_state'
            cutoff = np.nan
        count = int(present.sum())
        info = {'source_kind': kind, 'source_feature': feature, 'n_source_positive_bins': count,
                'activity_cutoff': cutoff, 'eligible': count >= 20}
        source_audit.append(info)
        if count >= 20:
            sources.append(present)
            source_meta.append(info)
    if not sources or not len(target_rows):
        raise ValueError(f'{sample}: no eligible sources or targets')
    source_matrix = sparse.csr_matrix(np.column_stack(sources).astype(np.float64))
    target_frame = frame.iloc[target_rows].reset_index(drop=True)
    labels = target_frame['target_type'].to_numpy()
    label_counts = pd.Series(labels).value_counts()
    whole_names = sorted(label_counts[label_counts >= 20].index)
    whole_matrix = sparse.csr_matrix(np.column_stack([labels == name for name in whole_names]).astype(np.float64))
    whole_meta = [{'target_kind': 'whole_celltype', 'target_feature': name, 'target_compartment': name,
                   'target_annotation_celltype': name, 'n_target_positive_bins': int(label_counts[name])} for name in whole_names]
    tme_meta, tme_columns = [], []
    for _, a in audit.loc[audit['feature_side'] == 'tme_target'].iterrows():
        if not a['eligible']:
            continue
        fid = a['feature_id']
        parent_cells = labels == a['parent']
        values = scores[fid].to_numpy()[target_rows]
        if not np.isfinite(values[parent_cells]).all() or not np.isfinite(a['cutoff']):
            raise ValueError(f'{sample}: non-finite parent scores or cutoff for {fid}')
        if parent_cells.sum() != a['n_parent']:
            raise ValueError(f'{sample}: parent-cell audit mismatch for {fid}')
        present = (values > a['cutoff']) & parent_cells
        if present.sum() != a['n_positive']:
            raise ValueError(f'{sample}: TME positivity audit mismatch for {fid}')
        tme_columns.append(present)
        tme_meta.append({'target_kind': 'tme_mp', 'target_feature': fid, 'target_compartment': fid.split('__')[0],
                         'target_annotation_celltype': a['parent'], 'n_target_positive_bins': int(present.sum())})
    tme_matrix = sparse.csr_matrix(np.column_stack(tme_columns).astype(np.float64)) if tme_columns else sparse.csr_matrix((len(target_rows), 0))
    pd.DataFrame(source_audit).to_csv(XOUT / f'tables/Auto_{sample}_source_feature_audit.csv', index=False)
    for name, matrix in [('source', source_matrix), ('whole', whole_matrix), ('tme', tme_matrix)]:
        sparse.save_npz(XOUT / f'intermediate/Auto_{sample}_{name}_membership.npz', matrix)
    return source_rows, target_rows, source_matrix, source_meta, target_frame, [(whole_matrix, whole_meta), (tme_matrix, tme_meta)]


