def contacts(args):
    validate_score_inputs()
    grouping = pd.read_csv(GROUPING)
    mp_order = grouping['mp'].tolist()
    if len(mp_order) != 17 or len(set(mp_order)) != 17 or set(mp_order) & {'MP2x', 'MP11c', 'MP18a'}:
        raise ValueError('Current 17-MP grouping contract violated')
    metadata = pd.read_csv(XOUT / 'intermediate/Auto_xenium_metadata.csv.gz')
    if set(metadata['coordinate_units']) != {'um'} or not np.all(metadata['um_per_pixel']==XENIUM_UM_PER_PIXEL):
        raise ValueError('Contacts require calibrated micrometre coordinates')
    metadata['malignant'] = strict_bool(metadata['malignant'])
    if metadata['row_index'].duplicated().any() or metadata['cell_id'].duplicated().any():
        raise ValueError('Duplicate metadata cell identity')
    if not np.isfinite(metadata[['spatial_x', 'spatial_y']].to_numpy()).all():
        raise ValueError('Non-finite spatial coordinates')
    all_results, diagnostics = [], []
    for sample_idx, sample in enumerate(pd.unique(metadata['patient'])):
        print(f'{sample}: build corrected contacts', flush=True)
        frame = metadata.loc[metadata['patient'] == sample].reset_index(drop=True)
        coords = frame[['spatial_x', 'spatial_y']].to_numpy(dtype=float)
        if len(np.unique(coords, axis=0)) != len(coords):
            raise ValueError(f'{sample}: duplicate coordinates')
        source_rows, target_rows, source_matrix, source_meta, target_frame, tests = build_sample(frame, sample, mp_order)
        source_tree = cKDTree(coords[source_rows])
        target_tree = cKDTree(coords[target_rows])
        np.savez_compressed(XOUT / f'intermediate/Auto_{sample}_graph.npz',
                            source_rows=source_rows, target_rows=target_rows, row_index=frame['row_index'].to_numpy(), coordinates=coords,
                            graph_definition='HD-equivalent Chebyshev windows; max(abs(dx),abs(dy)) <= 16*ring um')
        sample_results = []
        for ring in [1, 2, 3]:
            # The same physical Chebyshev window as the HD centroid graph,
            # evaluated directly on calibrated cell centroids (no binning).
            max_length = np.sqrt(2) * 16 * ring
            distances = source_tree.sparse_distance_matrix(target_tree, max_distance=16*ring, p=np.inf, output_type='coo_matrix')
            s, t = distances.row, distances.col
            adjacency = sparse.csr_matrix((np.ones(len(s)), (s, t)), shape=(len(source_rows), len(target_rows)))
            sparse.save_npz(XOUT / f'intermediate/Auto_{sample}_ring{ring}_adjacency.npz', adjacency)
            weights = (source_matrix.T @ adjacency).tocsr()
            slots = np.asarray(weights.sum(axis=1)).ravel()
            if len(s) == 0:
                raise ValueError(f'{sample}: no malignant/TME edges at ring {ring}')
            for target_idx, (membership, target_meta) in enumerate(tests):
                if not membership.shape[1]:
                    continue
                target_kind = target_meta[0]['target_kind']
                groups, mobility = local_groups(target_frame, target_kind == 'tme_mp')
                print(f'{sample} ring {ring} {target_kind}: {args.permutations} permutations per origin', flush=True)
                observed, expected, sd, p, origin_audit = empirical_test(weights, membership, groups, args.permutations,
                                  args.seed + sample_idx * 10000 + ring * 100 + target_idx, args.workers)
                for i, src in enumerate(source_meta):
                    for j, tgt in enumerate(target_meta):
                        # A programme can permute only within its parent. Its
                        # exposure is contacts to that parent, not to all TME.
                        if target_kind == 'tme_mp':
                            parent_cells = target_frame['target_type'].to_numpy() == tgt['target_annotation_celltype']
                            pair_slots = float(weights[i, parent_cells].sum())
                        else:
                            pair_slots = float(slots[i])
                        eligible = pair_slots >= 20
                        origin_fields = {}
                        for origin in range(len(groups)):
                            origin_fields[f'null_mean_origin_{origin + 1}'] = origin_audit['mean'][origin, i, j]
                            origin_fields[f'tail_ge_origin_{origin + 1}'] = origin_audit['ge'][origin, i, j]
                            origin_fields[f'tail_le_origin_{origin + 1}'] = origin_audit['le'][origin, i, j]
                            origin_fields[f'p_origin_{origin + 1}'] = origin_audit['p'][origin, i, j]
                        sample_results.append({**src, **tgt, **origin_fields, 'platform': 'xenium', 'sample': sample, 'ring': ring,
                            'mode_id': MODE[(src['source_kind'], target_kind)], 'observed_contacts': observed[i, j],
                            'null_mean_contacts': expected[i, j], 'null_sd_contacts': sd[i, j],
                            'log2_enrichment': np.log2((observed[i, j] + 0.5) / (expected[i, j] + 0.5)),
                            'p_empirical': p[i, j] if eligible else np.nan, 'eligible_pair': eligible,
                            'source_neighbour_slots': pair_slots, 'all_tme_neighbour_slots': slots[i],
                            'slot_scope': 'target_parent' if target_kind == 'tme_mp' else 'all_tme',
                            'n_permutations': args.permutations,
                            'n_permutations_total': args.permutations * len(groups),
                            'permutation_method': PERMUTATION_METHOD,
                            'origin_direction_concordant': origin_audit['direction_concordant'][i, j],
                            'spatial_unit': 'cell', 'max_edge_length_um': max_length,
                            'max_axis_distance_um':16*ring, 'graph_definition':'physical_queen_window'})
                diagnostics.append({'sample': sample, 'ring': ring, 'target_kind': target_kind,
                                    'n_observations': len(frame), 'n_malignant': len(source_rows), 'n_tme_targets': len(target_rows),
                                    'n_malignant_tme_edges': len(s), 'n_graph_edges': len(s), 'graph_scope':'malignant_to_tme',
                                    'minimum_movable_fraction': mobility, 'max_edge_length_um': max_length,
                                    'max_axis_distance_um':16*ring, 'graph_definition':'physical_queen_window'})
        sample_table = apply_fdr(pd.DataFrame(sample_results), 'p_empirical', 'fdr_sample', ['sample', 'mode_id', 'ring'])
        sample_table['direction'] = np.where(sample_table['log2_enrichment'] > 0, 'enriched', np.where(sample_table['log2_enrichment'] < 0, 'depleted', 'neutral'))
        sample_table.to_csv(XOUT / f'tables/Auto_{sample}_contacts.csv.gz', index=False)
        all_results.append(sample_table)
    result = pd.concat(all_results, ignore_index=True)
    result.to_csv(XOUT / 'tables/Auto_xenium_neighbourhood_interactions_by_sample.csv.gz', index=False)
    pd.DataFrame(diagnostics).to_csv(XOUT / 'tables/Auto_xenium_neighbourhood_sample_diagnostics.csv', index=False)
    parameters = {'version': VERSION, 'scoring': 'R UCell 2.2.0 raw counts', 'ucell_maxRank': 1500,
                  'malignant_mps': mp_order, 'positive_rule': 'sample/parent mean + 1 sample SD; strict greater-than',
                  'permutations': args.permutations, 'permutations_total': args.permutations * 4,
                  'permutation_method': PERMUTATION_METHOD,
                  'local_tile_um': 320, 'offsets_um': [[0,0],[160,0],[0,160],[160,160]],
                  'source_slot_rule': 'target_parent_for_tme_mp;all_tme_for_whole_celltype',
                  'min_source_positive': 20, 'min_whole_target': 20, 'min_parent': 20, 'min_tme_positive': 10, 'min_neighbour_slots': 20,
                  'primary_ring': 1, 'rings': [1,2,3], 'graph': 'HD-equivalent Chebyshev queen windows; max(abs(dx),abs(dy)) <= 16*ring micrometres',
                  'coordinate_source':'SOPA image pixels', 'coordinate_units':'um', 'um_per_pixel':XENIUM_UM_PER_PIXEL,
                  'seed': args.seed, 'workers': args.workers, 'crosswalk': CROSSWALK,
                  'state_source': str(ANNOT), 'states_reassigned': False,
                  'script_sha256': hashlib.sha256(Path(__file__).read_bytes()).hexdigest()}
    (XOUT / 'logs/Auto_contact_parameters.json').write_text(json.dumps(parameters, indent=2) + '\n')
    print('Corrected Xenium contact tables complete', flush=True)


def donor_statistics(frame):
    """Reduce dependent sections to one conservative directional donor test."""
    effects = frame['log2_enrichment'].to_numpy(dtype=float)
    p_values = frame['p_empirical'].to_numpy(dtype=float)
    concordant = bool(np.all(effects > 0) or np.all(effects < 0))
    donor_p = min(1.0, len(frame) * float(p_values.min())) if concordant else 1.0
    return {
        'platform': frame['platform'].iloc[0],
        'donor_id': frame['donor_id'].iloc[0],
        'section_ids': ';'.join(frame['sample_id']),
        'treatment_timepoints': ';'.join(sorted(frame['treatment_timepoint'].unique())),
        'n_sections_tested': len(frame),
        'n_section_fdr_0_05': int((frame['fdr_sample'] < .05).sum()),
        'section_direction_concordant': concordant,
        'p_empirical': donor_p,
        'log2_enrichment': float(effects.mean()),
        'signed_z': float(np.sign(effects.mean()) * norm.isf(donor_p / 2)),
    }


def aggregate_donors(frame):
    rows = []
    for key, sections in frame.groupby(KEYS + ['donor_id'], sort=False):
        rows.append({**dict(zip(KEYS, key[:-1])), **donor_statistics(sections)})
    return pd.DataFrame(rows)


def pooled_statistics(frame):
    """Equal-weight signed Stouffer evidence across independent donors."""
    if frame['donor_id'].duplicated().any():
        raise ValueError('A donor would receive more than one weight')
    effects = frame['log2_enrichment'].to_numpy(dtype=float)
    signed_z = frame['signed_z'].to_numpy(dtype=float)
    z = float(signed_z.sum() / np.sqrt(len(frame)))
    return {
        'n_donors_tested': len(frame),
        'n_sections_tested': int(frame['n_sections_tested'].sum()),
        'n_platforms': frame['platform'].nunique(),
        'n_hd_donors': int((frame['platform'] == 'visium_hd').sum()),
        'n_xenium_donors': int((frame['platform'] == 'xenium').sum()),
        'n_hd_sections': int(frame.loc[frame['platform'] == 'visium_hd', 'n_sections_tested'].sum()),
        'n_xenium_sections': int(frame.loc[frame['platform'] == 'xenium', 'n_sections_tested'].sum()),
        'donor_ids': ';'.join(frame['donor_id']),
        'section_ids': ';'.join(frame['section_ids']),
        'pooled_z': z,
        'pooled_p': max(float(2 * norm.sf(abs(z))), np.finfo(float).tiny) if len(frame) >= 2 else np.nan,
        'mean_log2_enrichment': float(effects.mean()),
        'n_enriched_donors': int((effects > 0).sum()),
        'n_depleted_donors': int((effects < 0).sum()),
        'direction_concordant': bool(np.all(effects > 0) or np.all(effects < 0)),
        'n_section_fdr_0_05': int(frame['n_section_fdr_0_05'].sum()),
    }


def paired_section_differences(valid):
    paired = valid.loc[valid['donor_id'] == PAIRED_DONOR]
    pre = paired.loc[paired['sample'] == 'FFPED1', KEYS + ['log2_enrichment', 'p_empirical']]
    post = paired.loc[paired['sample'] == 'FFPEA1', KEYS + ['log2_enrichment', 'p_empirical']]
    result = pre.merge(post, on=KEYS, suffixes=('_pre', '_post'), validate='one_to_one')
    result['post_minus_pre_log2_enrichment'] = result['log2_enrichment_post'] - result['log2_enrichment_pre']
    result['donor_id'] = PAIRED_DONOR
    result['interpretation'] = 'one_paired_donor_descriptive_only'
    return result


def validate_section_table(combined):
    if combined[KEYS + ['sample', 'platform']].isna().any().any():
        raise ValueError('Missing interaction keys or sample identity')
    if combined.duplicated(KEYS + ['sample_id']).any():
        raise ValueError('Duplicate per-section interaction would be double counted')
    eligible = combined['eligible_pair']
    numeric = ['p_empirical', 'log2_enrichment', 'n_permutations', 'fdr_sample',
               'observed_contacts', 'null_mean_contacts', 'source_neighbour_slots',
               'n_source_positive_bins', 'n_target_positive_bins']
    if not np.isfinite(combined.loc[eligible, numeric].to_numpy(dtype=float)).all():
        raise ValueError('An eligible section interaction contains missing or non-finite evidence')
    valid = combined.loc[eligible].copy()
    if (valid['n_permutations'] < 4999).any():
        raise ValueError('Input permutation resolution is lower than 4999')
    if not valid['p_empirical'].between(0, 1, inclusive='right').all():
        raise ValueError('Invalid empirical p values')
    if (valid['source_neighbour_slots'] < 20).any():
        raise ValueError('Eligible interaction lacks 20 contacts in its permitted target scope')
    if (valid[['observed_contacts', 'null_mean_contacts']] < 0).any().any():
        raise ValueError('Negative contact counts')
    expected_effect = np.log2((valid['observed_contacts'] + .5) / (valid['null_mean_contacts'] + .5))
    if not np.allclose(expected_effect, valid['log2_enrichment'], atol=1e-10, rtol=1e-10):
        raise ValueError('Contact counts and reported log2 enrichment disagree')
    return valid


def meta_analysis():
    tiers(MOUT)
    validate_score_inputs()
    xparams = json.loads((XOUT / 'logs/Auto_contact_parameters.json').read_text())
    if xparams['version'] != VERSION or xparams['coordinate_units'] != 'um':
        raise ValueError('Meta-analysis requires current calibrated Xenium contacts')
    if xparams['source_slot_rule'] != 'target_parent_for_tme_mp;all_tme_for_whole_celltype':
        raise ValueError('Xenium contacts lack target-parent-specific eligibility')
    xenium = pd.read_csv(XOUT / 'tables/Auto_xenium_neighbourhood_interactions_by_sample.csv.gz')
    hd = pd.read_csv(HDROOT / 'tables/Auto_spatial_interactions_by_sample.csv.gz')
    hd['platform'] = 'visium_hd'
    hd['spatial_unit'] = '16um_bin'
    hd = hd.loc[hd['mode_id'].isin(MODE.values())].copy()
    params = pd.read_csv(HDROOT / 'tables/Auto_spatial_interaction_parameters.csv').set_index('parameter')['value']
    expected_params = {
        'ucell_max_rank': 1500, 'bin_size_um': 16, 'spatial_permutation_block_um': 320,
        'top_genes_per_mp': 100, 'min_source_bins': 20, 'min_whole_target_bins': 20,
        'min_parent_bins_for_mp': 20, 'min_mp_positive_bins': 10, 'min_observed_neighbour_slots': 20,
    }
    if any(int(params[k]) != v for k, v in expected_params.items()) or params['mp_scoring'] != 'UCell on raw counts':
        raise ValueError('HD scoring, eligibility or null parameters differ from the implemented contract')
    if params['source_slot_rule'] != 'target_parent_for_tme_mp;all_tme_for_whole_celltype':
        raise ValueError('HD contact eligibility lacks parent-specific source slots')
    if params['permutation_method'] != PERMUTATION_METHOD or xparams['permutation_method'] != PERMUTATION_METHOD:
        raise ValueError('Both platforms must use separate tile-origin tests')
    if set(hd['permutation_method']) != {PERMUTATION_METHOD} or set(xenium['permutation_method']) != {PERMUTATION_METHOD}:
        raise ValueError('Section tables do not match the current permutation method')
    current_mps = pd.read_csv(GROUPING)['mp'].tolist()
    if len(current_mps) != 17 or len(set(current_mps)) != 17:
        raise ValueError('Current MP grouping is not an exact 17-MP collection')
    for platform, table in [('visium_hd', hd), ('xenium', xenium)]:
        if set(table.loc[table['source_kind'] == 'cancer_mp', 'source_feature']) != set(current_mps):
            raise ValueError(f'{platform}: section results do not contain exactly the current 17 MPs')
        if set(table.loc[table['source_kind'] == 'cancer_state', 'source_feature']) - set(STATES):
            raise ValueError(f'{platform}: section results contain unknown state labels')
    shared_cols = list(dict.fromkeys(KEYS + [
        'platform', 'sample', 'spatial_unit', 'p_empirical', 'log2_enrichment', 'eligible_pair',
        'n_permutations', 'fdr_sample', 'observed_contacts', 'null_mean_contacts', 'source_neighbour_slots',
        'n_source_positive_bins', 'n_target_positive_bins',
    ]))
    combined = pd.concat([hd[shared_cols], xenium[shared_cols]], ignore_index=True)
    combined['eligible_pair'] = strict_bool(combined['eligible_pair'])
    combined['sample_id'] = combined['platform'] + '::' + combined['sample']
    combined['orig.ident'] = combined['sample']
    design = read_sample_design()
    observed_design = set(map(tuple, combined[['platform', 'orig.ident']].drop_duplicates().to_numpy()))
    expected_design = set(map(tuple, design[['platform', 'orig.ident']].to_numpy()))
    if observed_design != expected_design:
        raise ValueError('Section contact tables differ from the approved sample design')
    combined = combined.merge(design, on=['platform', 'orig.ident'], validate='many_to_one', how='left')
    valid = validate_section_table(combined)
    combined.to_csv(MOUT / 'tables/Auto_harmonised_interactions_by_sample.csv.gz', index=False)
    design.to_csv(MOUT / 'tables/Auto_sample_donor_design.csv', index=False)
    donors = aggregate_donors(valid)
    donors = apply_fdr(donors, 'p_empirical', 'fdr_donor', ['donor_id', 'mode_id', 'ring'])
    donors.to_csv(MOUT / 'tables/Auto_harmonised_interactions_by_donor.csv.gz', index=False)

    availability = []
    for key, group in combined.groupby(KEYS, sort=False):
        eligible = group.loc[group['eligible_pair']]
        nh = eligible.loc[eligible['platform'] == 'visium_hd', 'donor_id'].nunique()
        nx = eligible.loc[eligible['platform'] == 'xenium', 'donor_id'].nunique()
        availability.append({
            **dict(zip(KEYS, key)), 'n_sections_observed': len(group),
            'n_sections_tested': len(eligible), 'n_hd_donors': nh, 'n_xenium_donors': nx,
            'cross_platform_eligible': nh >= 1 and nx >= 1,
            'replication_testable': nh >= 2 and nx >= 2,
        })
    pd.DataFrame(availability).to_csv(MOUT / 'tables/Auto_cross_platform_availability.csv', index=False)

    pooled, within, leave_one = [], [], []
    for key, group in donors.groupby(KEYS, sort=False):
        fields = dict(zip(KEYS, key))
        platform_stats = {}
        for platform, subset in group.groupby('platform'):
            stats = pooled_statistics(subset)
            within.append({**fields, 'platform': platform, **stats})
            platform_stats[platform] = stats
        if group['platform'].nunique() != 2:
            continue
        hd_stats = platform_stats['visium_hd']
        x_stats = platform_stats['xenium']
        testable = hd_stats['n_donors_tested'] >= 2 and x_stats['n_donors_tested'] >= 2
        hd_effect = hd_stats['mean_log2_enrichment']
        x_effect = x_stats['mean_log2_enrichment']
        agrees = bool(hd_effect * x_effect > 0)
        inferential_agrees = bool(hd_stats['pooled_z'] * x_stats['pooled_z'] > 0)
        effect_evidence_agrees = bool(hd_effect * hd_stats['pooled_z'] > 0 and x_effect * x_stats['pooled_z'] > 0)
        balanced_z = (hd_stats['pooled_z'] + x_stats['pooled_z']) / np.sqrt(2)
        # The conjunction tests each platform. A pooled p value alone cannot
        # establish replication, even when the two descriptive signs agree.
        replication_p = max(hd_stats['pooled_p'], x_stats['pooled_p']) if agrees and inferential_agrees and effect_evidence_agrees and testable else (1.0 if testable else np.nan)
        pooled.append({
            **fields, **pooled_statistics(group),
            'hd_mean_log2_enrichment': hd_effect, 'xenium_mean_log2_enrichment': x_effect,
            'hd_platform_p': hd_stats['pooled_p'], 'xenium_platform_p': x_stats['pooled_p'],
            'hd_platform_z': hd_stats['pooled_z'], 'xenium_platform_z': x_stats['pooled_z'],
            'inferential_direction_agrees': inferential_agrees,
            'effect_evidence_direction_agrees': effect_evidence_agrees,
            'platform_direction_agrees': agrees, 'replication_testable': testable,
            'replication_p': replication_p,
            'platform_balanced_z': balanced_z,
            'platform_balanced_p': max(float(2 * norm.sf(abs(balanced_z))), np.finfo(float).tiny) if testable else np.nan,
        })
        for donor_id in group['donor_id']:
            subset = group.loc[group['donor_id'] != donor_id]
            if subset['platform'].nunique() == 2:
                leave_one.append({**fields, 'omitted_donor': donor_id, **pooled_statistics(subset)})
    if not pooled:
        raise ValueError('No eligible interaction has both Xenium and HD evidence')
    pool_table = apply_fdr(pd.DataFrame(pooled), 'pooled_p', 'pooled_fdr', ['mode_id', 'ring'])
    pool_table = apply_fdr(pool_table, 'replication_p', 'replication_fdr', ['mode_id', 'ring'])
    pool_table = apply_fdr(pool_table, 'platform_balanced_p', 'platform_balanced_fdr', ['mode_id', 'ring'])
    pool_table['replicated_fdr_0_05'] = pool_table['replication_fdr'] < .05
    platform_table = apply_fdr(pd.DataFrame(within), 'pooled_p', 'pooled_fdr', ['platform', 'mode_id', 'ring'])
