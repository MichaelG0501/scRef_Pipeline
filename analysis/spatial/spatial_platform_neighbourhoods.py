def validate_score_inputs():
    """Stop reuse when a scoring input changed after the persisted scores."""
    inputs = [H5, ANNOT, GROUPING, MP_GENES,
              HDROOT / 'intermediate/Auto_visiumhd_tme_mp_gene_sets.rds',
              ROOT / 'analysis/spatial/xenium_hd_ucell_scores.R']
    newest_input = max(path.stat().st_mtime_ns for path in inputs)
    design = read_sample_design()
    for sample in design.loc[design['platform'] == 'xenium', 'orig.ident']:
        for path in [XOUT / f'intermediate/Auto_{sample}_ucell_scores.csv.gz',
                     XOUT / f'tables/Auto_{sample}_ucell_feature_audit.csv']:
            if path.stat().st_mtime_ns < newest_input:
                raise ValueError(f'Stale UCell output: {path}; rerun with SCREF_FORCE_REBUILD=TRUE')
