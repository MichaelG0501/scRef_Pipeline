    if feature.startswith('xenium_only__'):
        return feature.removeprefix('xenium_only__').replace('_', '/')
    if '__' in feature:
        parent, programme = feature.split('__', 1)
        return f'{names.get(parent, parent)} · {programme}'
    return names.get(feature, feature.replace('xenium_only__', ''))


