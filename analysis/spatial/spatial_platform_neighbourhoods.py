def read_h5_column(group, name):
    item = group[name]
    if isinstance(item, h5py.Group):
        categories = item['categories'].asstr()[:]
        codes = item['codes'][:]
        if (codes < 0).any():
            raise ValueError(f'Missing H5AD category: {name}')
        return categories[codes]
    return item.asstr()[:] if item.dtype.kind in {'O', 'S', 'U'} else item[:]


