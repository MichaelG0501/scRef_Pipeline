def validate_math():
    assert np.allclose(bh_adjust([.01,.04,.03]),[.03,.04,.04])
    assert np.isnan(bh_adjust([np.nan])[0])
    sections = pd.DataFrame({
        'p_empirical': [.02, .04], 'log2_enrichment': [1., 2.],
        'platform': ['visium_hd', 'visium_hd'], 'donor_id': ['paired', 'paired'],
        'sample_id': ['h::pre', 'h::post'], 'treatment_timepoint': ['pre', 'post'],
        'fdr_sample': [.04, .08],
    })
    paired = donor_statistics(sections)
    assert np.isclose(paired['p_empirical'], .04)
    assert paired['n_sections_tested'] == 2
    assert paired['log2_enrichment'] == 1.5
    sections.loc[1, 'log2_enrichment'] = -2.
    discordant = donor_statistics(sections)
    assert discordant['p_empirical'] == 1 and discordant['signed_z'] == 0
    assert discordant['log2_enrichment'] == -.5
    first = donor_statistics(sections.iloc[:1])
    second = dict(first, donor_id='independent', platform='xenium',
                  log2_enrichment=-1., signed_z=-first['signed_z'])
    opposite = pd.DataFrame([first, second])
    assert abs(pooled_statistics(opposite)['pooled_z']) < 1e-12
    assert pooled_statistics(opposite)['pooled_p'] == 1
    same = pd.DataFrame([first, dict(first, donor_id='independent', platform='xenium')])
    assert np.isclose(pooled_statistics(same)['pooled_z'], np.sqrt(2) * norm.isf(.01))
    assert np.isnan(pooled_statistics(same.iloc[:1])['pooled_p'])
    # Sections must never become independent replicate weights.
    mixed = pd.DataFrame([paired, dict(first, donor_id='independent', platform='xenium')])
    assert pooled_statistics(mixed)['n_donors_tested'] == 2
    assert pooled_statistics(mixed)['n_sections_tested'] == 3
    assert np.isclose(pooled_statistics(mixed)['mean_log2_enrichment'], 1.25)
    weights = sparse.csr_matrix([[1., 2., 0., 1.], [0., 1., 3., 0.]])
    membership = sparse.csr_matrix(np.ones((4, 1)))
    original = membership.toarray().copy()
    groups = [[np.arange(4)] for _ in range(4)]
    observed, expected, sd, p, audit = empirical_test(weights, membership, groups, 32, 999, 2)
    assert np.array_equal(observed, expected) and np.all(sd == 0) and np.all(p == 1)
    assert np.array_equal(original, membership.toarray())
    assert np.all(audit['n'] == 32) and np.all(audit['p'] == 1)
    membership = sparse.csr_matrix([[1.,0.], [1.,0.], [0.,1.], [0.,1.]])
    observed, expected, sd, p, audit = empirical_test(weights, membership, groups, 64, 111, 2)
    assert np.allclose(observed.sum(axis=1), expected.sum(axis=1))
    assert np.all((p > 0) & (p <= 1))
