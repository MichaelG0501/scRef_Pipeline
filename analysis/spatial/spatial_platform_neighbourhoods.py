def feature_label(feature):
    names = {'b.cell': 'B cells', 't.cell': 'T cells', 'endothelial': 'Endothelial',
             'fibroblast': 'Fibroblast', 'macrophage': 'Macrophage', 'dendritic': 'Dendritic',
             'mast': 'Mast', 'plasma': 'Plasma', 'nk': 'NK', 'nk.cell': 'NK cells',
             'erythrocyte': 'Erythrocyte', 'keratinocyte': 'Keratinocyte', 'lymph': 'Lymph',
             'neutrophil': 'Neutrophil', 'cd4': 'CD4 T', 'cd8': 'CD8 T'}
    if feature.startswith('xenium_only__'):
        return feature.removeprefix('xenium_only__').replace('_', '/')
    if '__' in feature:
        parent, programme = feature.split('__', 1)
        return f'{names.get(parent, parent)} · {programme}'
    return names.get(feature, feature.replace('xenium_only__', ''))


